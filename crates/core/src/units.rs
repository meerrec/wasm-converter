//! Перевод единиц раскладки OOXML в пиксели (96 dpi).
//!
//! Константы и функции дублировались между DOCX и XLSX; здесь канон. Пиксель
//! раскладки — 1/96 дюйма: от него считаются twips (1/1440 дюйма), полупункты
//! (1/144 дюйма), EMU (1/914 400 дюйма) и миллиметры.

/// Пикселей в типографском пункте: 96 dpi / 72 pt = 4/3.
pub const PX_PER_POINT: f32 = 96.0 / 72.0;

/// Английская метрическая единица (EMU): 914 400 на дюйм. При 96 dpi пиксель —
/// это ровно 9525 EMU.
pub const EMU_PER_PIXEL: f32 = 9525.0;

/// Твипов в пикселе при 96 dpi: 1440/96. Делить, а не умножать на 1/15:
/// произведение с округлением до целого твипа обязано попадать в целые
/// пиксели точно (4440 твипов — ровно 296 px), иначе ширина листа уезжает на
/// стотысячные доли.
pub const TWIPS_PER_PX: f32 = 15.0;

/// Миллиметров в пикселе раскладки: 96 dpi против 25.4 мм в дюйме.
///
/// Вход геометрии страниц для произвольного размера — `PageSize::Custom` в
/// миллиметрах (размеры DOCX/PPTX передаются через неё); обратно в точки их
/// возвращает сама геометрия.
pub const MM_PER_PX: f32 = 25.4 / 96.0;

/// Преобразовать длину из EMU в пиксели раскладки.
///
/// Так записаны размеры и смещения якорей изображений: `cx`/`cy` и `colOff`/
/// `rowOff` в `drawing*.xml`. Принимает `f32`: у DOCX значения целые (`i64`),
/// у XLSX парсер отдаёт `f32` — деление одно и то же.
#[must_use]
pub fn emu_to_px(emu: f32) -> f32 {
    emu / EMU_PER_PIXEL
}

/// Преобразовать twips в пиксели: 1 twip = 1/1440 дюйма, 1 пиксель = 1/96 дюйма.
/// Отношение: (1/1440) / (1/96) = 96/1440 = 1/15.
#[must_use]
pub fn twips_to_px(twips: f32) -> f32 {
    twips / TWIPS_PER_PX
}

/// Преобразовать полупункты в пиксели: 1 pt = 1/72 дюйма, 1 px = 1/96 дюйма.
/// Отношение: (1/72) / (1/96) = 96/72 = 4/3.
#[must_use]
pub fn half_points_to_px(half_points: f32) -> f32 {
    (half_points / 2.0) * PX_PER_POINT
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emu_conversion_is_exact_at_96_dpi() {
        // Один дюйм = 96 px = 914 400 EMU.
        assert!((emu_to_px(914_400.0) - 96.0).abs() < f32::EPSILON);
        assert!((emu_to_px(9525.0) - 1.0).abs() < f32::EPSILON);
    }

    #[test]
    fn twips_land_on_integer_pixels() {
        // 1440 твипов — ровно 96 px, 4440 — ровно 296 px.
        assert!((twips_to_px(1440.0) - 96.0).abs() < f32::EPSILON);
        assert!((twips_to_px(4440.0) - 296.0).abs() < f32::EPSILON);
    }

    #[test]
    fn half_points_match_point_scale() {
        // 24 полупункта = 12 pt = 16 px.
        assert!((half_points_to_px(24.0) - 16.0).abs() < f32::EPSILON);
    }
}
