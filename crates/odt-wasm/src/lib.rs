//! Отдельный wasm-модуль просмотра и экспорта ODT.
//!
//! Тянет `doc-converter-odf` (фича `odt`) — разбор текстового документа ODF 1.2
//! в модель `doc-converter-docx`, — и `doc-converter-docx` (раскладку по
//! метрикам шрифта и реестр шрифтов), поэтому в основной модуль не входит:
//! воркер подгружает его по требованию при открытии `.odt`, чтобы основной
//! модуль просмотрщика не платил за то, чем при работе с XLSX не пользуется
//! никто. Модуль самодостаточен — painter и SAB-аллокатор остаются в основном
//! модуле, а сюда приходит готовый `SharedArrayBuffer` от JS. Экспорт Markdown,
//! HTML и текста живёт здесь же, в модуле `export_api` (без intra-doc ссылки:
//! на нативном таргете крейт пуст, и ссылку не разрешил бы
//! `cargo doc --workspace`): у просмотрщика `.odt` этот модуль уже загружен, и
//! второй экземпляр парсера ради экспорта не нужен.
//!
//! Как и `crates/wasm`, крейт собирается только под `wasm32`: на нативном
//! таргете он пуст, и `cargo clippy --workspace --all-targets` проходит без
//! выбора цели.

#![cfg(target_arch = "wasm32")]

pub mod export_api;
pub mod odt_api;
pub mod stream_api;
pub mod text_api;
