//! Отдельный wasm-модуль просмотра XLSB.
//!
//! Тянет `doc-converter-xlsb` — чтение бинарных частей OOXML-пакета в модель
//! `doc-converter-xlsx`, — поэтому в основной модуль не входит: воркер
//! подгружает его по требованию при открытии `.xlsb`, чтобы основной модуль
//! просмотрщика не платил за парсер, которым при работе с XLSX не пользуется
//! никто. Кадр рисует общий `doc_converter_xlsx::paint`, потому что модель
//! книги у XLSB та же. Модуль самодостаточен — painter и SAB-аллокатор
//! остаются в основном модуле, а сюда приходит готовый `SharedArrayBuffer`
//! от JS. Экспорта текста здесь НЕТ: у XLSX/XLSB нет текстовой выгрузки.
//!
//! Как и `crates/wasm`, крейт собирается только под `wasm32`: на нативном
//! таргете он пуст, и `cargo clippy --workspace --all-targets` проходит без
//! выбора цели.

#![cfg(target_arch = "wasm32")]

pub mod stream_api;
pub mod xlsb_api;
