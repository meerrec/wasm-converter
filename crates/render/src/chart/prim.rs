//! Примитивы раскладки диаграммы — внутренний IR canvas- и PDF-бэкендов
//! (ADR-0011).
//!
//! Это не проводной формат: кадр (`DisplayList`, `DL_VERSION = 4`) примитивов
//! диаграмм не несёт, их получает бэкенд напрямую из [`crate::chart::layout`].
//! Числа — в единицах переданного прямоугольника: для canvas это физические
//! пиксели, для PDF — пункты после масштаба страницы. Выравнивание текста
//! разрешает бэкенд (canvas — `textAlign`/`textBaseline`, PDF — метрики шрифта).

use crate::display_list::Color;

/// Точка в единицах прямоугольника диаграммы.
pub type Point = (f64, f64);

/// Горизонтальное выравнивание текста относительно точки привязки.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TextAlign {
    Left,
    Center,
    Right,
}

/// Примитив диаграммы; бэкенд рисует примитивы в порядке списка — порядок
/// задаёт наложение и должен совпадать у canvas и PDF.
#[derive(Debug, Clone, PartialEq)]
pub enum ChartPrim {
    /// Залитый прямоугольник: столбцы и образцы легенды.
    Rect {
        x: f64,
        y: f64,
        w: f64,
        h: f64,
        fill: Color,
    },
    /// Ломаная; `closed` замыкает путь. Замкнутость нужна рамке области
    /// построения: canvas-путь штрихует её закрытым контуром, и у открытой
    /// ломаной угол в стыке концов срезался бы стыком обрезки.
    Polyline {
        points: Vec<Point>,
        stroke: Color,
        width: f64,
        closed: bool,
    },
    /// Залитый многоугольник: ряд площадной диаграммы.
    Polygon { points: Vec<Point>, fill: Color },
    /// Круг: маркер точечной диаграммы.
    Circle {
        cx: f64,
        cy: f64,
        r: f64,
        fill: Color,
    },
    /// Сектор круговой диаграммы. Углы — в радианах, система экранная (`y`
    /// вниз), угол растёт по часовой стрелке — как у
    /// `CanvasRenderingContext2D::arc`; `from` — начало, `to` — конец.
    Sector {
        cx: f64,
        cy: f64,
        r: f64,
        from: f64,
        to: f64,
        fill: Color,
    },
    /// Текст: `(x, y)` — привязка по горизонтали (см. `align`) на базовой линии
    /// (alphabetic), `size` — кегль в единицах прямоугольника.
    Text {
        x: f64,
        y: f64,
        text: String,
        size: f64,
        align: TextAlign,
        fill: Color,
    },
}
