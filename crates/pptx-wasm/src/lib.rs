//! Отдельный wasm-модуль просмотра и экспорта PPTX.
//!
//! Тянет `doc-converter-pptx` — разбор презентации и раскладку слайдов по
//! метрикам шрифта, — поэтому в основной модуль не входит: воркер подгружает
//! его по требованию при открытии `.pptx`, чтобы основной модуль просмотрщика
//! не платил за то, чем при работе с XLSX не пользуется никто. Модуль
//! самодостаточен — painter и SAB-аллокатор остаются в основном модуле, а сюда
//! приходит готовый `SharedArrayBuffer` от JS. Экспорт Markdown, HTML, текста
//! и PDF живёт здесь же, в модуле `export_api`: у просмотрщика `.pptx` этот
//! модуль уже загружен, и второй экземпляр парсера ради экспорта не нужен.
//!
//! Как и `crates/wasm`, крейт собирается только под `wasm32`: на нативном
//! таргете он пуст, и `cargo clippy --workspace --all-targets` проходит без
//! выбора цели.

#![cfg(target_arch = "wasm32")]

pub mod export_api;
pub mod pptx_api;
pub mod stream_api;
