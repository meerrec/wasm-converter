//! Отдельный wasm-модуль просмотрщика DOCX.
//!
//! Тянет `doc-converter-docx` — раскладку по метрикам шрифта и реестр шрифтов, —
//! поэтому в основной модуль не входит: воркер подгружает его по требованию при
//! открытии `.docx`, чтобы основной модуль просмотрщика не платил за то, чем
//! при работе с XLSX не пользуется никто. Модуль самодостаточен — painter и
//! SAB-аллокатор остаются в основном модуле, а сюда приходит готовый
//! `SharedArrayBuffer` от JS.
//!
//! Как и `crates/wasm`, крейт собирается только под `wasm32`: на нативном
//! таргете он пуст, и `cargo clippy --workspace --all-targets` проходит без
//! выбора цели.

#![cfg(target_arch = "wasm32")]

