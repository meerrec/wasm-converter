// Контракт воркерного рендер-адаптера: единственная точка, через которую
// `WorkerCore` управляет кадром.
//
// У кадра два места жизни, и до этого контракта ядро ветвилось по `backend` в
// каждом обработчике (`init`, `resize`, `render`, `frame-ack`, `close`). Теперь
// различие живёт в двух реализациях: `OffscreenRenderAdapter` рисует в воркере,
// `ForwardingRenderAdapter` только собирает DisplayList и отправляет его на
// main. Ядро не знает, какая реализация под ним, поэтому поля этого интерфейса
// менять нельзя: они и есть граница между «рисуем здесь» и «отправляем туда».

import type { RenderTarget } from '../../execution/plan.js';

/**
 * Управление рендером на стороне воркера.
 *
 * Жизненный цикл: `start` один раз на `init` (ошибка здесь — ошибка
 * инициализации воркера), дальше `request` на каждый запрос кадра, `resize` на
 * смену размеров холста, `ack` на возврат буфера с main и `stop` при
 * закрытии/сбое.
 */
export interface RenderAdapter {
  /** Где рисуется кадр: от этого зависит, кто шлёт `tick` и кто владеет буфером. */
  readonly target: RenderTarget;
  /**
   * Поднять рендер: painter и шрифты для воркерного пути, цикл отправки — для
   * main-пути. `canvas` приходит только воркерному пути.
   */
  start(canvas: OffscreenCanvas | null): Promise<void>;
  /** Запросить кадр: сборка случится одна на микрозадачу. */
  request(): void;
  /** Пересчитать холст под новые размеры (CSS-пиксели и DPR). */
  resize(cssW: number, cssH: number, dpr: number): void;
  /** Main вернул буфер кадра после отрисовки. */
  ack(slot: number, buffer: ArrayBuffer): void;
  /** Остановить цикл; вызывается на закрытии и на ошибке инициализации. */
  stop(): void;
  /** Холст, если рендер идёт в воркере; `null` в main-режиме. */
  readonly canvas: OffscreenCanvas | null;
}
