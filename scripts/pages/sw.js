// Единственный сервис-воркер сайта, и стоит он в корне не по вкусовщине.
// Навигацию рамки обслуживает тот воркер, который контролирует родителя, а не
// тот, чья область совпадает с URL рамки: воркер в области `/viewer/` закрыл бы
// изоляцию демо, но навигацию `editor.html` не увидел бы вовсе (проверено
// экспериментально), и документ движка остался бы без COEP. Поэтому воркер один
// и в корне, а прежний `viewer/coi-serviceworker.js` больше не публикуется.
//
// Работы у него две: снять с браузера кэши прежних версий сайта и отдать
// ответам заголовки, которых на GitHub Pages взять негде. Сам он не кэширует
// ничего: ровно по этому URL (`/sw.js` в корне) раньше лежал PWA-воркер
// вендорного лендинга с предкешированной оболочкой (`document-editor-*`) и
// рантайм-кэшем движковых ассетов. URL и область те же, поэтому браузер
// подменит тот воркер этим файлом при обычной проверке обновления, а его кэши
// остались бы мёртвым грузом — отдавали бы посетителю страницы, которых в новом
// сайте уже нет.
//
// Молчание в ответ на сообщения движка (он спрашивает VERSION и CLIENT_COUNT,
// чтобы «залечить и перезагрузить») — намеренное: расспросы обрываются по
// таймауту, и обновление просто не трогает открытый документ.

// Установка сразу боевая: держать старый воркер «ожидающим» незачем — его кэши
// всё равно подлежат удалению, а новая версия страницы к ним не обращается.
self.addEventListener('install', (event) => {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Сносим все кэши без разбора: сам воркер не кэширует ничего, так что
      // любой найденный кэш оставлен прежней версией сайта и указывает на её
      // же сборку.
      const names = await caches.keys();
      await Promise.all(names.map((name) => caches.delete(name)));
      // claim нужен для вкладок, которые всё ещё держит прежний воркер: без него
      // он до перезагрузки продолжал бы отвечать из удаляемых кэшей.
      await self.clients.claim();
    })(),
  );
});

// ── Заголовки изоляции для документов ────────────────────────────────────────

/**
 * Умеет ли браузер встроить кадр в изолированную страницу.
 *
 * Формулировка одна на три места — здесь, в `examples/viewer/src/lib/isolation.ts`
 * (источник правды: предикат экспортируется оттуда) и в inline-скрипте
 * `scripts/pages/index.html`; разъехаться им нельзя, потому что воркер изолирует
 * страницу на следующем заходе, а страницы решают, поднимать ли воркер вовсе.
 *
 * Проверяется `userAgentData`, а не атрибут `credentialless` у
 * `HTMLIFrameElement`: в воркере DOM нет, `HTMLIFrameElement` тут `undefined`
 * (проверено), а API клиент-хинтов экспонировано и в Worker'ах (проверено:
 * `'userAgentData' in self.navigator === true` в Chromium). Прокси точный —
 * браузера, знающего `credentialless`, но не `userAgentData`, сегодня нет: в
 * Chromium есть и то и другое, а Firefox и Safari не знают ни одного.
 *
 * Проверка стоит здесь, а не только на страницах, потому что воркер регистрирует
 * и сам движок: его страница `editor.html` (код регистрации — в бандле
 * `assets/editor-*.js`) зовёт `./sw.js` мимо наших страниц. Без этой строки Safari
 * всё равно поднял бы воркер, со второго захода получил бы заголовки и потерял бы
 * маршрут `#/eurooffice`.
 */
function supportsCredentiallessFrames() {
  return 'userAgentData' in self.navigator;
}

/**
 * Запрос к демо (`…/viewer/…`) — от этого зависит значение COEP.
 *
 * Префикс считается от области воркера, а не прописан константой: воркер лежит в
 * корне сайта (и на Pages, и на staging-сервере), и имя репозитория в области уже
 * есть. Область берётся в обработчике, а не на верхнем уровне файла: там она
 * доступна не во всех браузерах.
 */
let demoPrefix = null;

function isDemoRequest(url) {
  demoPrefix ??= new URL('viewer/', self.registration.scope).pathname;
  return new URL(url).pathname.startsWith(demoPrefix);
}

/**
 * Ответ с заголовками изоляции.
 *
 * Тело не буферизуем: `new Response(response.body, …)` оставляет поток потоком,
 * так что 36-мегабайтный `x2t.wasm.br` едет в браузер, не собираясь целиком в
 * памяти воркера.
 *
 * COOP + COEP нужны документу: только они включают cross-origin isolation, без
 * которой не бывает `SharedArrayBuffer`. CORP со `cross-origin` спрашивают
 * вложенные документы (рамку редактора берёт изолированная страница демо, а
 * документ движка — сам с себя уже изолированный), а одного CORP для кадра мало:
 * Chromium режет вложенный документ без COEP собственного ответа
 * (`ERR_BLOCKED_BY_RESPONSE`, `blockedReason=coep-frame-resource-needs-coep-header`).
 *
 * Значение COEP разное, и это не косметика. Демо (`…/viewer/…`) — `require-corp`:
 * её изоляция та самая, ради которой всё и затевалось (кольца SAB в просмотрщике).
 * Движку — `credentialless`: изолированный родитель такой кадр впускает
 * (проверено: рамка редактора внутри изолированного демо остаётся
 * `crossOriginIsolated`), а CORP у no-cors подресурсов credentialless не требует —
 * они едут без учётных данных, а сайт статический и куки ему не нужны. Изоляция от
 * смены значения не теряется: credentialless включает её ровно так же.
 *
 * Неуспешные ответы и ответы со `status === 0` отдаются как есть: у opaque
 * (в том числе `opaqueredirect` — так выглядит редирект навигации, чей fetch
 * идёт с внутренним `redirect: manual`) заголовки переписать нельзя, а пересборка
 * 4xx/5xx отвязала бы тело от сети ради ничего.
 */
async function withIsolationHeaders(request) {
  const response = await fetch(request);
  if (response.status === 0 || !response.ok) {
    return response;
  }
  const headers = new Headers(response.headers);
  headers.set('Cross-Origin-Resource-Policy', 'cross-origin');
  // COEP ставится всем ответам, а не только навигациям: его спрашивают не только
  // у документа рамки, но и у скрипта воркера — того, которого движок заводит
  // через `new Worker(…)` (`sdkjs/common/spell/spell/spell.js`,
  // `sdkjs/common/wasm/x2t/x2t.worker.js`). Воркер-скрипт, доставшийся без
  // заголовка, Chromium режет с тем же `coep-frame-resource-needs-coep-header`,
  // что и кадр без COEP: без x2t не конвертируются таблицы, без spell — не
  // работает проверка орфографии. Значение берётся по пути, а не по типу запроса:
  // политика ответа обязана совпасть с политикой того, кто его просит, — иначе
  // воркер демо (страница изолирована `require-corp`) упрётся в то же правило с
  // другой стороны.
  headers.set(
    'Cross-Origin-Embedder-Policy',
    isDemoRequest(request.url) ? 'require-corp' : 'credentialless',
  );
  if (request.mode === 'navigate') {
    headers.set('Cross-Origin-Opener-Policy', 'same-origin');
  }
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

self.addEventListener('fetch', (event) => {
  // Без поддержки — не отвечаем ничего: ни заголовков, ни лишнего хопа на 566 МБ
  // статики. Изолировать в Safari/Firefox значило бы убить маршрут `#/eurooffice`
  // (см. `supportsCredentiallessFrames`), а собственный воркер движка остановить
  // нашими страницами нельзя — регистрацию заказывает он сам.
  if (!supportsCredentiallessFrames()) return;

  // Раньше здесь стоял ранний выход для всего, кроме навигаций: считалось, что
  // подресурсам заголовки не нужны, а лишний хоп сквозь воркер на 566 МБ
  // статики — чистая потеря. Оказалось наоборот: подресурсы движка спрашивают
  // заголовки сами (CORP — как вложенный документ, COEP — как воркер-скрипт),
  // без них движок теряет конвертер x2t, и приёмка `scripts/pages/check-route.mjs`
  // падает на xlsx, оставаясь зелёной на docx (см. `withIsolationHeaders`).
  event.respondWith(withIsolationHeaders(event.request));
});
