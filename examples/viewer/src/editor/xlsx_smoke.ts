import assert from 'node:assert/strict';
import JSZip from 'jszip';
import type { EditorArgs } from './types.js';
import type { EditorContext } from './commands.js';
import { executeXlsx } from './xlsx.js';

const zip = new JSZip();
const context: EditorContext = { zip, format: 'xlsx', args: {}, clipboardFormat: null, clipboardText: '' };
async function run(command: string, args: EditorArgs = {}) {
  context.args = args;
  const result = await executeXlsx(context, command);
  console.log(command, result.changed ?? false, result.value ?? result.message ?? '');
  return result;
}
async function xml(path: string) {
  const file = context.zip.file(path);
  assert.ok(file, path);
  return (await file.async('string'));
}
